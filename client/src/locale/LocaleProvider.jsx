const LocaleContext = createContext(null)

function readStoredLocale() {
  try {
    const stored = JSON.parse(localStorage.getItem(LOCALE_STORAGE_KEY) || '{}')
    return {
      language: stored.language === 'es' ? 'es' : 'en',
      currency: stored.currency === 'MXN' ? 'MXN' : 'USD',
    }
  } catch {
    return { language: 'en', currency: 'USD' }
  }
}

export function LocaleProvider({ children }) {
  const [settings, setSettings] = useState(() => readStoredLocale())

  useEffect(() => {
    localStorage.setItem(LOCALE_STORAGE_KEY, JSON.stringify(settings))
  }, [settings])

  const value = useMemo(() => ({
    ...settings,
    locale: settings.language === 'es' ? 'es-MX' : 'en-US',
    setLanguage(language) {
      setSettings(current => ({ ...current, language: language === 'es' ? 'es' : 'en' }))
    },
    setCurrency(currency) {
      setSettings(current => ({ ...current, currency: currency === 'MXN' ? 'MXN' : 'USD' }))
    },
    t(key, variables = {}) {
      const template = messages[settings.language][key] || messages.en[key] || key
      return Object.entries(variables).reduce(
        (output, [variable, value]) => output.replace(`{${variable}}`, String(value)),
        template
      )
    },
  }), [settings])

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  const context = useContext(LocaleContext)

  if (!context) {
    throw new Error('useLocale must be used within a LocaleProvider')
  }

  return context
}
